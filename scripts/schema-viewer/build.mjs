import {build,transform} from 'esbuild';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const output=path.resolve(here,'../../designs/browser/vendor');
await mkdir(output,{recursive:true});
const result=await build({absWorkingDir:here,entryPoints:['entry.js'],bundle:true,minify:true,format:'esm',platform:'browser',target:['safari16','chrome110'],define:{'process.env.NODE_ENV':'"production"'},alias:{'@stoplight/markdown-viewer':path.join(here,'markdown.js'),'@stoplight/mosaic':path.join(here,'mosaic.js')},outfile:path.join(output,'schema-viewer.js'),metafile:true,legalComments:'eof'});
const css=await Promise.all(['node_modules/@stoplight/mosaic/styles.css','node_modules/@stoplight/mosaic/themes/default.css','viewer.css'].map(file=>readFile(path.join(here,file),'utf8')));
const combined=css.join('\n').replaceAll(':root',':host');
await writeFile(path.join(output,'schema-viewer.css'),(await transform(combined,{loader:'css',minify:true})).code);
const packages=new Map();
for(const input of Object.keys(result.metafile.inputs)){
 if(!input.includes('node_modules/'))continue;
 let dir=path.dirname(path.resolve(here,input));
 while(dir!==here&&dir!==path.dirname(dir)){
  try{const pkg=JSON.parse(await readFile(path.join(dir,'package.json'),'utf8'));if(pkg.name&&pkg.version){packages.set(dir,pkg);break}}catch{}
  dir=path.dirname(dir);
 }
}
// Include full bundled-package notices, rather than just the top-level license.
packages.set(path.join(here,'node_modules/@stoplight/mosaic'),JSON.parse(await readFile(path.join(here,'node_modules/@stoplight/mosaic/package.json'),'utf8')));
let notices='Locally bundled JSON Schema viewer.\nGenerated by scripts/schema-viewer/build.mjs.\n\n';
for(const [dir,pkg] of [...packages].sort((a,b)=>a[1].name.localeCompare(b[1].name))){
 let license='';for(const file of ['LICENSE','LICENSE.md','LICENSE.txt','license','license.md','license.txt','License','License.txt','UNLICENSE']){try{license=await readFile(path.join(dir,file),'utf8');break}catch{}}
 if(!license){try{license=await readFile(path.join(here,'licenses',pkg.name.replace(/^@/,'').replaceAll('/','-')+'.txt'),'utf8')}catch{}}
 if(!license){console.error('Missing license notice for '+pkg.name);process.exitCode=1;continue}
 notices+='===== '+pkg.name+' '+pkg.version+' ('+pkg.license+') =====\n'+license+'\n\n';
}
if(process.exitCode)throw Error('Missing third-party notices');
await writeFile(path.join(output,'schema-viewer.LICENSE'),notices);
console.log('Built local Schema viewer with '+packages.size+' bundled-package notices.');
